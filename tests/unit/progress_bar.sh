#!/bin/bash
# tests/unit/progress_bar.sh — tests for bar_filled(), bar_color_code(), status_label()

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/../helpers.sh"
source "$SCRIPT_DIR/../../lib/compute.sh"

describe "bar_filled — fill count at 12-char width"
assert_eq "0"    "$(bar_filled 0)"     "0% → 0 filled"
assert_eq "0"    "$(bar_filled 1)"     "1% → 0 filled (integer div)"
assert_eq "0"    "$(bar_filled 8)"     "8% → 0 filled (8*12/100=0, integer div)"
assert_eq "6"    "$(bar_filled 50)"    "50% → 6 filled"
assert_eq "7"    "$(bar_filled 60)"    "60% → 7 filled"
assert_eq "9"    "$(bar_filled 75)"    "75% → 9 filled"
assert_eq "9"    "$(bar_filled 83)"    "83% → 9 filled (83*12/100=9, integer div)"
assert_eq "10"   "$(bar_filled 90)"    "90% → 10 filled (90*12/100=10, integer div)"
assert_eq "11"   "$(bar_filled 94)"    "94% → 11 filled"
assert_eq "12"   "$(bar_filled 100)"   "100% → 12 filled"

describe "bar_filled — custom width"
assert_eq "5"    "$(bar_filled 50 10)"   "50% at width 10 → 5"
assert_eq "20"   "$(bar_filled 50 40)"   "50% at width 40 → 20"

describe "bar_color_code — tier thresholds"
assert_eq "32"        "$(bar_color_code 0)"    "0% → green (32)"
assert_eq "32"        "$(bar_color_code 49)"   "49% → green (32)"
assert_eq "33"        "$(bar_color_code 50)"   "50% → yellow (33)"
assert_eq "33"        "$(bar_color_code 74)"   "74% → yellow (33)"
assert_eq "38;5;208"  "$(bar_color_code 75)"   "75% → orange (38;5;208)"
assert_eq "38;5;208"  "$(bar_color_code 89)"   "89% → orange"
assert_eq "31"        "$(bar_color_code 90)"   "90% → red (31)"
assert_eq "31"        "$(bar_color_code 94)"   "94% → red (31)"
assert_eq "41;37;1"   "$(bar_color_code 95)"   "95% → red bg bold (41;37;1)"
assert_eq "41;37;1"   "$(bar_color_code 100)"  "100% → red bg bold"

describe "status_label — tier labels"
assert_eq "healthy"     "$(status_label 0)"    "0% → healthy"
assert_eq "healthy"     "$(status_label 49)"   "49% → healthy"
assert_eq "ATTENTION"   "$(status_label 50)"   "50% → ATTENTION"
assert_eq "ATTENTION"   "$(status_label 74)"   "74% → ATTENTION"
assert_eq "CHECKPOINT"  "$(status_label 75)"   "75% → CHECKPOINT"
assert_eq "CHECKPOINT"  "$(status_label 89)"   "89% → CHECKPOINT"
assert_eq "CRITICAL"    "$(status_label 90)"   "90% → CRITICAL"
assert_eq "CRITICAL"    "$(status_label 94)"   "94% → CRITICAL"
assert_eq "EMERGENCY"   "$(status_label 95)"   "95% → EMERGENCY"
assert_eq "EMERGENCY"   "$(status_label 100)"  "100% → EMERGENCY"
